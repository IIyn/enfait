/// Folder, relative to the composition, holding the library.
pub const LIB_DIR: &str = "lib";

pub struct FontFace {
    pub family: &'static str,
    pub file: &'static str,
    /// Fixed weight (`"400"`) or range of a variable font (`"100 900"`).
    pub weight: &'static str,
    pub italic: bool,
    /// Width range of a variable font (`"62% 125%"`).
    pub stretch: Option<&'static str>,
    data: &'static [u8],
}

macro_rules! face {
    ($family:literal, $file:literal, $weight:literal, $italic:literal $(, $stretch:literal)?) => {
        FontFace {
            family: $family,
            file: $file,
            weight: $weight,
            italic: $italic,
            stretch: face!(@stretch $($stretch)?),
            data: include_bytes!(concat!("../../../assets/motion/fonts/", $file)),
        }
    };
    (@stretch $s:literal) => { Some($s) };
    (@stretch) => { None };
}

